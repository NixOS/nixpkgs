#!/usr/bin/env nix-shell
#!nix-shell -i bash --packages nix curl jq
# shellcheck shell=bash

set -o errexit -o nounset -o pipefail

cd "$(dirname "$0")"

readonly plugin_name="${1:?Usage: update-grafana-plugin.sh <plugin-name>}"
readonly sources="$plugin_name/sources.toml"

api_response="$(curl --fail --silent --show-error "https://grafana.com/api/plugins/${plugin_name}")"
readonly api_response
version="$(jq --compact-output --exit-status '.version | select(type == "string" and length > 0)' <<<"$api_response")"
readonly version
packages="$(jq --compact-output --exit-status '.packages | select(type == "object" and length > 0)' <<<"$api_response")"
readonly packages

build_package() {
  local package="$1" pkg hash url
  pkg="$(jq --compact-output --exit-status --argjson package "$package" '.[$package]' <<<"$packages")" || return
  url="$(jq --raw-output --exit-status '.downloadUrl | select(type == "string" and length > 0)' <<<"$pkg")" || return
  if [[ "$url" == /* ]]; then
    url="https://grafana.com$url"
  fi
  if ! hash="$(jq --raw-output --exit-status '.sha256 // empty' <<<"$pkg")"; then
    # Some packages only have an MD5 hash. Download them to compute SHA-256.
    hash="$(nix-prefetch-url --type sha256 --name "$plugin_name" "$url")" || return
  fi
  hash="$(nix --extra-experimental-features nix-command hash convert --hash-algo sha256 --to sri "$hash")" || return
  url="$(jq --compact-output --null-input --arg url "$url" '$url')" || return
  printf '\n[packages.%s]\nhash = "%s"\nurl = %s\n' "$package" "$hash" "$url"
}

build_packages() {
  local keys package
  keys="$(jq --compact-output 'keys[]' <<<"$packages")" || return
  while IFS= read -r package; do
    build_package "$package" || return
  done <<<"$keys"
}

package_records="$(build_packages)"
readonly package_records
readonly contents="# Generated by update-grafana-plugin.sh. Do not manually edit.
version = $version
$package_records"

mkdir --parents -- "$plugin_name"
echo "$contents" >"$sources"
