#!/usr/bin/env nix-shell
#! nix-shell -i bash --pure -p cacert curl jq nix

set -euo pipefail

cd "$(readlink -e "$(dirname "${BASH_SOURCE[0]}")")"

repo="superradcompany/microsandbox"

version=$(curl -sfL "https://api.github.com/repos/$repo/releases/latest" | jq -r .tag_name)
version=${version#v}
if [[ -z "$version" || "$version" == "null" ]]; then
  echo "could not determine the latest release" >&2
  exit 1
fi

# Upstream publishes one audited bundle per supported platform.
systems=(x86_64-linux aarch64-linux aarch64-darwin)
assets=(microsandbox-linux-x86_64.tar.gz microsandbox-linux-aarch64.tar.gz microsandbox-darwin-aarch64.tar.gz)

# Check that the release carries every bundle before rewriting sources.nix.
checksums=$(curl -sfL "https://github.com/$repo/releases/download/v$version/checksums.sha256")
for asset in "${assets[@]}"; do
  grep -qF "  $asset" <<<"$checksums" || {
    echo "release v$version has no $asset" >&2
    exit 1
  }
done

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

{
  echo "# Generated by ./update.sh. Do not edit by hand."
  echo "# Last updated: $(date +%F)"
  echo '{ fetchurl }:'
  echo '{'
  for i in "${!systems[@]}"; do
    system=${systems[$i]}
    asset=${assets[$i]}
    url="https://github.com/$repo/releases/download/v$version/$asset"

    hash=$(nix-prefetch-url "$url")
    hash=$(nix --extra-experimental-features nix-command hash convert --to sri --hash-algo sha256 "$hash")

    echo "  $system = {"
    echo "    version = \"$version\";"
    echo "    src = fetchurl {"
    echo "      url = \"$url\";"
    echo "      hash = \"$hash\";"
    echo "    };"
    echo "  };"
  done
  echo '}'
} >"$tmp"

mv "$tmp" sources.nix
