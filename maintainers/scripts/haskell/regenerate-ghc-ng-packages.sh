#!/usr/bin/env nix-shell
#!nix-shell -i bash -p cabal2nix -I nixpkgs=.

# Regenerate the cabal2nix expressions for the GHC packages built by
# `pkgs/development/compilers/ghc/ng`.
#
# Each package gets a directory:
#
#     common/packages/<name>/generated-package.nix   <- written by this script
#     common/packages/<name>/*.patch                 <- applied by the overlay
#
# The output is *verbatim* cabal2nix apart from two mechanical steps: a "do not
# edit" header, and dropping the `src = /nix/store/...` line, which pins the
# store path of whichever source tree happened to be realised when the script
# ran. `src` and `postUnpack` come from the overlay in `common/overlay.nix`
# instead, along with the patches sitting beside the generated file.
#
# `generated-package.nix` should never be hand-edited. If a package needs a
# change, make it in the overlay or add a patch beside it -- that keeps
# regeneration a clean diff.
#
# Usage:
#   maintainers/scripts/haskell/regenerate-ghc-ng-packages.sh [<ghc-version-attr>]
#
# e.g. `... 9.14`. Defaults to 9.14.

set -euo pipefail

VERSION="${1:-9.14}"
ROOT="$(git rev-parse --show-toplevel)"
# Per-release: cabal2nix bakes the version into every expression, so a 9.14
# expression against a 9.15 tree builds the wrong thing.
if [ "$VERSION" = head ]; then DIR=head; else DIR="$VERSION"; fi
OUT="$ROOT/pkgs/development/compilers/ghc/ng/$DIR/packages"

echo "Realising the GHC $VERSION source tree..." >&2
SRC=$(nix-build --no-out-link \
  -E "((import $ROOT {}).callPackages $ROOT/pkgs/development/compilers/ghc/ng {}).\"$VERSION\".ghcSrc")

echo "Source: $SRC" >&2

# subdirectory:attribute-name
PACKAGES=(
  # Build-platform tools (`_tools`).
  utils/deriveConstants:deriveConstants
  utils/genapply:genapply
  utils/genprimopcode:genprimopcode
  utils/unlit:unlit
  utils/ghc-toolchain:ghc-toolchain
  utils/ghc-toolchain/exe:ghc-toolchain-bin
  # Boot libraries and the compiler itself.
  libraries/ghc-platform:ghc-platform
  libraries/ghc-boot:ghc-boot
  libraries/ghc-boot-th:ghc-boot-th
  libraries/ghc-heap:ghc-heap
  libraries/ghc-compact:ghc-compact
  libraries/ghc-bignum:ghc-bignum
  libraries/ghc-internal:ghc-internal
  libraries/ghc-experimental:ghc-experimental
  libraries/ghc-prim:ghc-prim
  libraries/base:base
  libraries/ghci:ghci
  libraries/template-haskell:template-haskell
  libraries/system-cxx-std-lib:system-cxx-std-lib
  libraries/integer-gmp:integer-gmp
  compiler:ghc
  ghc:ghc-bin
  rts:rts
  utils/ghc-pkg:ghc-pkg
  # `Name: iserv` upstream; stable-haskell renamed it to `ghc-iserv` on their
  # fork, but the binary is installed under the `ghc-` name by the assembly.
  utils/iserv:iserv
  utils/remote-iserv:remote-iserv
  utils/hsc2hs:hsc2hs
  utils/hpc:hpc-bin
  utils/runghc:runghc
  utils/hp2ps:hp2ps
  utils/haddock:haddock
  utils/haddock/haddock-api:haddock-api
  utils/haddock/haddock-library:haddock-library
)

# Write one generated expression, reading cabal2nix output on stdin.
#
# Two mechanical steps, and nothing else -- the body stays verbatim cabal2nix:
#
#   o a "do not edit" header, mirroring the one hackage2nix puts on
#     `pkgs/development/haskell-modules/hackage-packages.nix`. These files are
#     equally regenerated, and equally tempting to patch by hand.
#   o dropping the pinned `src`; see the header of this script.
#
# The `src` match is on any absolute path, not just `/nix/store/`: a patched
# package is generated from a temporary copy, so cabal2nix pins
# `/tmp/nix-shell-.../tmp.XXXX` -- a path that will not even exist afterwards.
#
# It must stay a *path* match. The pinned-Hackage expressions beside these carry
# a real, wanted `src = fetchzip { ... }`, and matching the bare attribute would
# decapitate that block and leave its `url` and `sha256` dangling.
writeGenerated() {
  local dest="$1"
  {
    echo "# ${dest##*/} is auto-generated by regenerate-ghc-ng-packages.sh -- DO NOT EDIT MANUALLY!"
    echo
    grep -v '^  src = /'
  } > "$dest"
}

mkdir -p "$OUT"
export HOME="$(mktemp -d)"
trap 'rm -rf "$HOME"' EXIT

for entry in "${PACKAGES[@]}"; do
  dir="${entry%%:*}"
  name="${entry##*:}"
  if [ ! -d "$SRC/$dir" ]; then
    echo "  SKIP $name ($dir not present in this version)" >&2
    continue
  fi
  # Flags a package needs for its *base* expression to describe a buildable
  # package at all. Distinct from the variant flags below, which produce extra
  # files: these change what `generated-package.nix` itself says.
  baseFlags=()
  case "$name" in
    # `ghc-internal.cabal` marks itself `buildable: False` unless exactly one
    # bignum backend is selected, and all three default to off. Without this
    # cabal2nix faithfully reports an unbuildable package, the derivation
    # succeeds, and it installs nothing.
    ghc-internal) baseFlags=(--flag=bignum-native) ;;
  esac

  # cabal2nix must see the *patched* package. A patch can change
  # `build-depends` -- `ghc-toolchain-bin`'s JSON emitter adds `aeson` -- and
  # generating from the pristine tree then produces an expression that is
  # missing a dependency the build will demand:
  #
  #     Encountered missing or private dependencies: aeson
  #
  # Easy to miss, because it only shows up for packages whose patch touches
  # `build-depends`; every other patched package generates identically either
  # way. So the tree is copied and patched here rather than read in place.
  pkgdir="$SRC/$dir"
  if compgen -G "$OUT/$name/*.patch" > /dev/null; then
    work="$(mktemp -d)"
    cp -r "$SRC/$dir/." "$work/"
    chmod -R u+w "$work"
    for p in "$OUT/$name"/*.patch; do
      if ! patch -d "$work" -p1 --silent < "$p"; then
        echo "  FAIL $name (patch $(basename "$p") does not apply)" >&2
        rm -rf "$work"
        continue 2
      fi
    done
    pkgdir="$work"
  fi

  if ! out=$(cabal2nix "${baseFlags[@]}" "$pkgdir" 2>/dev/null); then
    echo "  FAIL $name" >&2
    continue
  fi
  mkdir -p "$OUT/$name"
  printf '%s\n' "$out" | writeGenerated "$OUT/$name/generated-package.nix"
  echo "  ok   $name" >&2

  # Some packages are generated more than once, under different cabal flags,
  # because the flag changes the dependency list and so cannot be expressed as
  # a configure flag alone:
  #
  #   -bootstrap    stage1, compiling against the *old* base. `ghc-boot` then
  #                 depends on `ghc-boot-th-next` rather than `ghc-boot-th`.
  #   -interpreter  stage2, with GHCi's evaluator compiled into the compiler.
  #                 `ghc-bin` then gains `ghci` and `haskeline`; without it
  #                 Template Haskell does not work.
  case "$name" in
    ghc-boot|ghci|ghc|ghc-boot-th-next)
      if v=$(cabal2nix "${baseFlags[@]}" --flag=bootstrap "$pkgdir" 2>/dev/null); then
        printf '%s\n' "$v" | writeGenerated "$OUT/$name/generated-package-bootstrap.nix"
        echo "  ok   $name (bootstrap)" >&2
      fi
      ;;
  esac
  case "$name" in
    ghc|ghc-bin|ghci)
      if v=$(cabal2nix "${baseFlags[@]}" --flag=internal-interpreter "$pkgdir" 2>/dev/null); then
        printf '%s\n' "$v" | writeGenerated "$OUT/$name/generated-package-interpreter.nix"
        echo "  ok   $name (interpreter)" >&2
      fi
      ;;
  esac
  # The patched copy, if we made one.
  if [ "$pkgdir" != "$SRC/$dir" ]; then rm -rf "$pkgdir"; fi
done

echo "Wrote $OUT" >&2

# A generated expression with no library, no executable and no dependencies is
# almost always a cabal flag problem rather than a package that genuinely builds
# nothing. `ghc-internal` is the standing example: its .cabal says
#
#   if !flag(bignum-native) && !flag(bignum-gmp) && !flag(bignum-ffi)
#     buildable: False
#
# and all three default to off, so cabal2nix faithfully reports an unbuildable
# package. The derivation then *succeeds* and installs nothing, which only
# surfaces much later as a missing symbol somewhere else.
echo >&2
echo "Checking for suspiciously empty expressions..." >&2
empty=0
for d in "$OUT"/*/; do
  f="$d/generated-package.nix"
  [ -f "$f" ] || continue
  if ! grep -qE 'HaskellDepends|isLibrary|isExecutable|SystemDepends' "$f"; then
    echo "  EMPTY: $(basename "$d") -- check its cabal flags" >&2
    empty=1
  fi
done
if [ "$empty" = 0 ]; then
  echo "  none" >&2
else
  # Fatal, not advisory. An empty expression is a *silent* failure downstream --
  # the derivation builds happily and installs nothing -- so it must not be
  # possible to regenerate into that state and not notice.
  echo >&2
  echo "error: regenerated an empty expression; add its flags to baseFlags above" >&2
  exit 1
fi
